function getFinalPrice(book) {
  if (book.isOnOrder) return 0;
  return Number((book.price * (1 - book.discount / 100)).toFixed(2));
}

function renderCategories() {
  const t = translations[currentLang];
  const categories = ['all', ...new Set(books.map(b => b.category))];
  const container = document.getElementById('categoriesList');
  container.innerHTML = categories.map(cat => `
    <button onclick="filterCategory('${cat}')" 
      class="px-3 py-1.5 text-xs font-semibold rounded-full border transition ${currentCategory === cat ? 'bg-indigo-900 text-white border-indigo-900' : 'bg-gray-100 text-gray-600 hover:bg-gray-200 border-transparent'}">
      ${cat === 'all' ? t.allCategories : cat}
    </button>
  `).join('');
}

function filterCategory(cat) {
  currentCategory = cat;
  renderCategories();
  renderBooks();
}

function renderBooks() {
  const t = translations[currentLang];
  const search = document.getElementById('searchInput').value.toLowerCase();
  const sort = document.getElementById('sortSelect').value;
  const maxPrice = parseFloat(document.getElementById('priceRange').value);
  const minRating = parseFloat(document.getElementById('ratingFilter').value);

  let filtered = books.filter(b => {
    const finalPrice = getFinalPrice(b);
    const matchesCat = (currentCategory === 'all' || b.category === currentCategory);
    const matchesSearch = (b.title.toLowerCase().includes(search) || b.author.toLowerCase().includes(search));
    const matchesPrice = b.isOnOrder || finalPrice <= maxPrice;
    const matchesRating = b.rating >= minRating;

    return matchesCat && matchesSearch && matchesPrice && matchesRating;
  });

  if (sort === 'price-asc') filtered.sort((a,b) => getFinalPrice(a) - getFinalPrice(b));
  if (sort === 'price-desc') filtered.sort((a,b) => getFinalPrice(b) - getFinalPrice(a));
  if (sort === 'discount') filtered.sort((a,b) => b.discount - a.discount);
  if (sort === 'rating-desc') filtered.sort((a,b) => b.rating - a.rating);

  const grid = document.getElementById('booksGrid');
  grid.innerHTML = filtered.map(b => {
    const finalPrice = getFinalPrice(b);
    const inWishlist = wishlist.includes(b.id);
    return `
      <div class="bg-white rounded-xl shadow-sm hover:shadow-md transition overflow-hidden flex flex-col relative group">
        <button onclick="toggleWishlist(${b.id})" class="absolute top-3 right-3 z-10 w-8 h-8 rounded-full bg-white/80 backdrop-blur-sm flex items-center justify-center text-rose-500 hover:scale-110 transition shadow-sm">
          <i class="${inWishlist ? 'fa-solid' : 'fa-regular'} fa-heart"></i>
        </button>
        <img src="${b.image}" alt="${b.title}" class="h-48 w-full object-cover cursor-pointer" onclick="openBookModal(${b.id})">
        <div class="p-4 flex-1 flex flex-col justify-between">
          <div>
            <div class="flex items-center justify-between">
              <span class="text-xs text-indigo-600 font-semibold">${b.category}</span>
              <span class="text-xs font-bold text-yellow-500"><i class="fa-solid fa-star"></i> ${b.rating.toFixed(1)}</span>
            </div>
            <h3 class="font-bold text-gray-900 mt-1 cursor-pointer hover:text-indigo-600" onclick="openBookModal(${b.id})">${b.title}</h3>
            <p class="text-xs text-gray-500">${b.author}</p>
          </div>
          <div class="mt-4 flex items-center justify-between">
            <div>
              ${b.isOnOrder ? `
                <span class="text-xs font-bold bg-amber-100 text-amber-800 px-2 py-0.5 rounded-full">${t.onOrderStatus}</span>
              ` : `
                ${b.discount > 0 ? `<span class="text-xs text-gray-400 line-through">${b.price.toFixed(2)} zł</span>` : ''}
                <div class="text-lg font-bold text-indigo-900">${finalPrice.toFixed(2)} zł</div>
              `}
            </div>
            <button onclick="addToCart(${b.id})" class="${b.isOnOrder ? 'bg-indigo-900 hover:bg-indigo-800 text-white' : 'bg-yellow-400 hover:bg-yellow-500 text-indigo-950'} px-3 py-1.5 rounded-lg text-xs font-bold transition">
              ${t.addToCart}
            </button>
          </div>
        </div>
      </div>
    `;
  }).join('');
}

