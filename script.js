function handleReviewSubmit(e, bookId) {
  e.preventDefault();
  const book = books.find(b => b.id === bookId);
  if (!book) return;

  const name = document.getElementById('revName').value;
  const rating = parseFloat(document.getElementById('revRating').value);
  const text = document.getElementById('revText').value;

  if (!book.reviews) book.reviews = [];
  book.reviews.push({ name, rating, text });

  const sum = book.reviews.reduce((acc, r) => acc + r.rating, 0);
  book.rating = Number((sum / book.reviews.length).toFixed(1));

  saveBooksToStorage();
  renderBooks();
  showToast(translations[currentLang].reviewSuccess);
  openBookModal(bookId);
}

