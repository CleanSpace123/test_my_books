// --- Cart Logic ---
function addToCart(id) {
  const book = books.find(b => b.id === id);
  if (!book) return;

  const item = cart.find(i => i.id === id);
  if (item) item.qty++;
  else cart.push({ id, qty: 1 });

  saveCartToStorage();
  updateCart();
  showToast(`«${book.title}» ${translations[currentLang].addedToCartToast}`);
}

function updateCart() {
  const t = translations[currentLang];
  const count = cart.reduce((acc, i) => acc + i.qty, 0);
  document.getElementById('cartCount').innerText = count;

  const container = document.getElementById('cartItems');
  let total = 0;

  container.innerHTML = cart.map(i => {
    const book = books.find(b => b.id === i.id);
    if (!book) return '';
    
    const price = getFinalPrice(book);
    total += price * i.qty;

    return `
      <div class="flex items-center gap-3 border-b pb-3">
        <img src="${book.image}" class="w-12 h-16 object-cover rounded">
        <div class="flex-1">
          <h4 class="font-bold text-sm">${book.title}</h4>
          <p class="text-xs text-gray-500">
            ${book.isOnOrder ? `<span class="font-bold text-amber-800 bg-amber-100 px-1.5 py-0.5 rounded">${t.onOrderStatus}</span>` : `${price.toFixed(2)} zł`}
          </p>
        </div>
        <div class="flex items-center border rounded">
          <button onclick="changeQty(${book.id}, -1)" class="px-2 py-0.5 text-xs">-</button>
          <span class="px-2 text-xs font-bold">${i.qty}</span>
          <button onclick="changeQty(${book.id}, 1)" class="px-2 py-0.5 text-xs">+</button>
        </div>
      </div>
    `;
  }).join('');

  document.getElementById('cartTotal').innerText = `${total.toFixed(2)} zł`;
}

function changeQty(id, delta) {
  const item = cart.find(i => i.id === id);
  if (!item) return;
  item.qty += delta;
  if (item.qty <= 0) cart = cart.filter(i => i.id !== id);
  saveCartToStorage();
  updateCart();
}

