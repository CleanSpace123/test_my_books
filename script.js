function handleSaveBook(e) {
  e.preventDefault();

  const editingId = document.getElementById('editingBookId').value;
  const isOnOrder = document.getElementById('newIsOnOrder').checked;

  const bookData = {
    title: document.getElementById('newTitle').value,
    author: document.getElementById('newAuthor').value,
    category: document.getElementById('newCategory').value,
    price: isOnOrder ? 0 : Number(parseFloat(document.getElementById('newPrice').value || 0).toFixed(2)),
    discount: isOnOrder ? 0 : Number(document.getElementById('newDiscount').value),
    rating: Number(document.getElementById('newRating').value),
    image: document.getElementById('newImage').value,
    desc: document.getElementById('newDesc').value,
    isOnOrder: isOnOrder
  };

  if (editingId) {
    const index = books.findIndex(b => b.id === Number(editingId));
    if (index !== -1) {
      books[index] = { ...books[index], ...bookData };
    }
  } else {
    books.push({
      id: Date.now(),
      ...bookData,
      reviews: []
    });
  }

  saveBooksToStorage();
  renderCategories();
  renderBooks();
  renderAdminTable();
  closeAddBookModal();
}

function showToast(message) {
  const container = document.getElementById('toastContainer');
  const toast = document.createElement('div');
  toast.className = 'bg-gray-900 text-white text-xs font-semibold px-4 py-3 rounded-xl shadow-lg flex items-center gap-2 pointer-events-auto transition-all transform translate-y-2 opacity-0';
  toast.innerHTML = `<i class="fa-solid fa-circle-check text-emerald-400 text-sm"></i> ${message}`;
  
  container.appendChild(toast);
  
  setTimeout(() => toast.classList.remove('translate-y-2', 'opacity-0'), 10);
  setTimeout(() => {
    toast.classList.add('opacity-0', 'translate-y-2');
    setTimeout(() => toast.remove(), 300);
  }, 3000);
}

function checkout() {
  const t = translations[currentLang];
  if (!cart.length) return showToast(t.cartEmpty);
  
  let total = cart.reduce((acc, i) => {
    const book = books.find(b => b.id === i.id);
    return acc + (book ? getFinalPrice(book) * i.qty : 0);
  }, 0);

  document.getElementById('checkoutModalTotal').innerText = `${total.toFixed(2)} zł`;
  toggleCart();
  document.getElementById('checkoutModal').classList.remove('hidden');
}

